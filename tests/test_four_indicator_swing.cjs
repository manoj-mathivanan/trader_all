const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context=vm.createContext({document:{querySelector:()=>null,addEventListener(){}},location:{hash:'#backtests'}});
const app=fs.readFileSync('dashboard/web/app.js','utf8');
vm.runInContext(app.slice(0,app.indexOf("$('#modal').addEventListener('close'")),context);
vm.runInContext(fs.readFileSync('dashboard/web/four-indicator-swing.js','utf8'),context);
const run=s=>vm.runInContext(s,context);
run(`state={screens:[],jobs:[],runs:[],four_indicator_schema:{properties:{}},reference_only:false};`);
assert.match(run('strategyPicker()'),/four_indicator_swing/);
assert.doesNotMatch(run('nav.map(x=>x[0]).join(",")'),/options/);
assert.doesNotMatch(run('workspaceViews.join(",")'),/options/);
run(`modal=(title,body)=>{globalThis.dialog={title,body};};selectedRun={};`);
run(`showFourIndicatorSwingResult({id:'aabbccddeeff',rule_label:'All four',universe:'niftytotalmarket',config:{name:'Daily swing',capital:100000},metrics:{return_pct:2,net_pnl:2000,trade_count:1,max_drawdown_pct:1,win_rate:100,modeled_fees:20,modeled_slippage:20,skipped_entries:0},curve:[{date:'2026-10-01',equity:100000},{date:'2026-10-09',equity:102000}],manifest:[{}],excluded:[],exclusion_reasons:{},warnings:['<source>'],trades:[{symbol:'A<B>',signal_date:'2026-10-01',entry_date:'2026-10-02',exit_date:'2026-10-09',entry:100,exit:102,quantity:1000,pnl:2000,reason:'Supertrend'}]});`);
assert.match(context.dialog.body,/Daily equity swing/);
assert.match(context.dialog.body,/Stock trade ledger/);
assert.match(context.dialog.body,/data-action="trade-chart" data-run="aabbccddeeff" data-trade="0"/);
assert.match(context.dialog.body,/A&lt;B&gt;/);
assert.match(context.dialog.body,/&lt;source&gt;/);
assert.match(context.dialog.body,/data-four-indicator-rerun/);
assert.match(context.dialog.body,/Backtest settings/);
const coverage=run(`fourIndicatorCoverage({stock_coverage:{'A<B>':{first_available:'2018-01-01',eligible_from:'2018-05-25',last_available:'2026-10-09'}},history_fragments:{'A<B>':{ignored_candles:25}}})`);
assert.match(coverage,/A&lt;B&gt;/);
assert.match(coverage,/2018-05-25/);
assert.match(coverage,/Earlier candles ignored/);
console.log('Daily four-indicator strategy uses the standard picker, saved reports, settings and rerun controls; no Options navigation.');
run(`state.four_indicator_paper_scenarios=[{id:'rsi',strategy_name:'four_indicator_swing',status:'active',universe:'niftytotalmarket',start_session:'2026-10-12',replay_through:'2026-10-24',reconstruction_notice:'Historical replay <test>',config:{name:'RSI paper',capital:1000000,max_positions:5,rule_set:'rsi',auto_run:true,run_hour:16,run_minute:15},ledger:{cash:800000,positions:{'A<B>':{entry:100,entry_date:'2026-10-13',signal_date:'2026-10-12',quantity:2000,entry_cost:200000}},marks:{'A<B>':101},orders:[],trades:[]},metrics:{final_equity:1002000}}];selectedPaperStrategy='four_indicator_swing';selectedPaperScenario='rsi';`);
assert.match(run('paperPortfolioCards()'),/RSI paper/);
assert.match(run('paperPortfolioCards()'),/Equal capital slots/);
assert.doesNotMatch(run('paperPortfolioCards()'),/undefined|NaN|Scalping/);
assert.match(run('fourIndicatorPaperDetail()'),/Historical replay &lt;test&gt;/);
assert.match(run('fourIndicatorPaperDetail()'),/A&lt;B&gt;/);
assert.match(run('paperPath("cycle")'),/four_indicator_swing\/paper\/cycle\?portfolio_id=rsi/);
assert.match(run('strategyPicker("four_indicator_swing","new-paper-strategy",true)'),/Four-indicator daily swing/);
console.log('Indicator paper scenarios render in the existing Paper trade page with independent selection and replay labels.');

(async()=>{
  run(`state.jobs=[{type:'Paper daily cycle',status:'running'}];api=async()=>({history_start:'2025-01-01',history_end:'2026-10-09'});`);
  await run('newFourIndicatorSwing()');
  assert.match(context.dialog.body,/>Queue backtest<\/button>/);
  assert.doesNotMatch(context.dialog.body,/<button[^>]*type="submit"[^>]*disabled/);
  run(`state.four_indicator_schema.properties={rule_set:{},max_positions:{},rsi_threshold:{},bollinger_multiplier:{}};field=(k,schema,value)=>'<input name="'+k+'" value="'+value+'">';`);
  await run('newFourIndicatorSwing()');
  assert.match(context.dialog.body,/name="rule_set" value="bollinger"/);
  assert.match(context.dialog.body,/name="max_positions" value="10"/);
  assert.match(context.dialog.body,/name="rsi_threshold" value="65"/);
  assert.match(context.dialog.body,/name="bollinger_multiplier" value="2.5"/);
  await run(`newFourIndicatorSwing({comparison_run_id:'aabbccddeeff',rule_set:'bollinger',max_positions:5})`);
  assert.match(context.dialog.body,/name="max_positions" value="5"/);
  assert.match(context.dialog.body,/name="rsi_threshold" value="70"/);
  assert.match(context.dialog.body,/name="bollinger_multiplier" value="2"/);
  console.log('Four-indicator backtests remain available while a paper cycle runs.');
})().catch(error=>{console.error(error);process.exitCode=1;});
